    public partial class Consultar1 : Form
    {
        public Consultar1()
        {
            InitializeComponent();
        }


        private void TxtBuscador_KeyPress(object sender, KeyPressEventArgs e)
        {
            // Permitir teclas de control (Backspace, Enter, etc.)
            if (char.IsControl(e.KeyChar))
                return;

            // Permitir solo letras y números
            if (!char.IsLetterOrDigit(e.KeyChar))
            {
                e.Handled = true; // Cancela la entrada
                MessageBox.Show("Solo se permiten letras y números.", "Validación", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
        }

        // También limitar a 18 caracteres
        private void TxtBuscador_TextChanged(object sender, EventArgs e)
        {
            if (TxtBuscador.Text.Length > 18)
            {
                TxtBuscador.Text = TxtBuscador.Text.Substring(0, 18);
                TxtBuscador.SelectionStart = TxtBuscador.Text.Length;
                MessageBox.Show("Máximo 18 caracteres permitidos.", "Validación", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
        }


        private void BtnBuscar_Click(object sender, EventArgs e)
        {
            string datoABuscar = TxtBuscador.Text.Trim();

            if (string.IsNullOrEmpty(datoABuscar)) return;

            // Usamos la conexión global que guardamos desde el Login
            using (SqlConnection conn = new SqlConnection(LoginForm.CadenaDeConexionGlobal))
            {
                // Buscamos si existe el registro (ejemplo buscando por CURP o ID)
                string query = "SELECT COUNT(*) FROM BENEFICIARIO WHERE id_curp_beneficiario = @dato";

                using (SqlCommand cmd = new SqlCommand(query, conn))
                {
                    cmd.Parameters.AddWithValue("@dato", datoABuscar);

                    try
                    {
                        conn.Open();
                        int existeRegistro = (int)cmd.ExecuteScalar();

                        if (existeRegistro > 0)
                        {
                            // =========================================================
                            // EL REGISTRO YA EXISTE
                            // ¡OJO AQUÍ!: Cambia "NombreDeTuFormularioDeEdicion" por el nombre real 
                            // del formulario que tiene tu DataGridView. No uses Consultar1.
                            // =========================================================
                            BeneficiarioForm formEdicion = new BeneficiarioForm(datoABuscar);
                            formEdicion.Show();
                        }
                        else
                        {
                            // =========================================================
                            // EL REGISTRO ES NUEVO
                            // CORRECCIÓN: Le quitamos el "(datoABuscar)" para que se abra 
                            // 100% en blanco, tal como lo necesitas.
                            // =========================================================
                            Registrar formNuevo = new Registrar();
                            formNuevo.Show();
                        }

                        // Cerramos el buscador flotante
                        this.Close();
                    }
                    catch (SqlException ex)
                    {
                        MessageBox.Show("Error en la búsqueda: " + ex.Message);
                    }
                }
            }
        }

